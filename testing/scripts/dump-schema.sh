#!/usr/bin/env bash
# Refreshes testing/schema/schema.sql from a database that has the current
# schema (normally the development database). Structure only: no rows, no
# owners and no grants are copied.
#
#   SCHEMA_SOURCE_URL=postgres://... testing/scripts/dump-schema.sh
#
# Use a direct (non-pooled) connection string. pg_dump 17 or newer is needed.
set -euo pipefail

: "${SCHEMA_SOURCE_URL:?Set SCHEMA_SOURCE_URL to the database to copy the schema from}"

here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../schema/schema.sql"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

pg_dump "$SCHEMA_SOURCE_URL" --schema-only --no-owner --no-privileges --no-comments -f "$tmp"

{
  echo "-- OpenBookings schema snapshot."
  echo "--"
  echo "-- Generated by testing/scripts/dump-schema.sh on $(date -u +%Y-%m-%d). Do not edit by hand:"
  echo "-- migrations newer than this snapshot are applied on top of it by testing/scripts/setup.ts."
  echo "-- The Neon-only extensions pg_session_jwt and vector are left out; no table uses them."
  echo
  # \restrict / \unrestrict are psql meta-commands that pg_dump 17.6+ adds; older
  # psql versions reject them. The two extensions are not on stock Postgres.
  grep -vE '^\\(un)?restrict |^CREATE EXTENSION IF NOT EXISTS (pg_session_jwt|vector) |^-- Name: (pg_session_jwt|vector); Type: EXTENSION' "$tmp"
} > "$out"

echo "Wrote $out ($(grep -c '^CREATE TABLE' "$out") tables)."
